JD_PRACTICES = [
    ('Lead with the outcome, not a wish list', 'Open with what the person will achieve in their first six months. Candidates respond to the work, not to a long list of tools.'),
    ('Separate must-have from nice-to-have', 'Keep must-haves to four or five real requirements. A long list of musts narrows the pool and hides the people who could grow into the role.'),
    ('Write skills as things a person can show', 'Say "built and run pipelines in production" instead of "knowledge of data". It is easier to test, and fairer to compare.'),
    ('Use plain, inclusive language', 'Avoid jargon, slogans and gendered phrases. Say clearly what the working pattern, location and level of seniority are.'),
    ('Describe the team and how work gets done', 'Who will they work with, how are decisions made, and what does a normal week look like?'),
    ('Be clear about the process', 'Tell candidates the steps, who they will meet and how long it takes. A clear process is one of the strongest signs of a good employer.'),
    ('Build the interview from the JD', 'Every must-have gets at least one question or exercise, with a simple scoring guide agreed before the first interview.'),
]

